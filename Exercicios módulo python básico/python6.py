## Exibição de informações com input

print("Digite a sua idade:")
idade = int(input())
print("Digite a sua altura:")
altura = float(input())
print("Digite seu nome: ")
name = str(input())

print(f"Nome: {name}")
print(f"Tipo: {type(name)}")

print(f"Idade: {idade}")
print(f"Tipo: {type(idade)}")

print(f"Altura: {altura}")
print(f"Tipo: {type(altura)}")

