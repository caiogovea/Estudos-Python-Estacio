## Divisões

print("Digite o primeiro número inteiro: ")
n1 = int(input())

print("Digite o segundo número inteiro: ")
n2 = int(input())

quocienteI = n1 // n2
print(f"Quociente Inteiro: {quocienteI}") 

divisaoS = n1 / n2
print(f"Divisão normal: {divisaoS}")

resto = n1 % n2
print(f"Resto: {resto}")

