## Operações Aritméticas

a = 20
b = 6

soma = a + b
subtracao = a - b   
multiplicacao = a * b
divisao = a / b
divisaointeira = a // b
resto = a % b
potencia = a ** b

print("Soma:", soma)
print("Subtração:", subtracao)
print("Multiplicação:", multiplicacao)
print(f"Divisão: {divisao:.2f}")
print(f"Divisão Inteira: {divisaointeira:.2f}")
print(f"Resto: {resto:.2f}")
print(f"Potência: {potencia:.2f}")